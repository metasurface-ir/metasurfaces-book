"""Produce the English workshop from the supplied, shared Persian application."""
import html
import json
from pathlib import Path
import re

WORKSHOP_ASSET = 'metasurface-chapter-3.html'
WORKSHOP_ROUTE = 'unit-cell-workshop'
ROOT = Path(__file__).resolve().parents[1]
PERSIAN_TEXT = re.compile(r'[\u0600-\u06ff\u200c\u200f]+(?:[ \t.,؛،!?():/−–-]+[\u0600-\u06ff\u200c\u200f]+)*')
BLOCKS = re.compile(r'(<script\b[^>]*>.*?</script>|<style>.*?</style>)', re.S)


def localize_workshop(source, language):
    if language == 'fa':
        return source
    lexicon = json.loads((ROOT / 'translations/chapter03-workshop-en.json').read_text(encoding='utf-8'))

    def replace(part):
        if part.startswith('<style>') or part.startswith('<script id="cst-data"'):
            return part
        is_script = part.startswith('<script')
        entries = lexicon['js' if is_script else 'static']

        def translate(match):
            # Replacement strings in the shared script are quoted in strings,
            # sometimes inside HTML attribute values generated by that script.
            value = entries[match[0]]
            if is_script:
                return value.replace('\\', '\\\\').replace("'", '&#39;').replace('"', '&quot;')
            return html.escape(value, quote=True)

        return PERSIAN_TEXT.sub(translate, part)

    result = ''.join(replace(part) for part in BLOCKS.split(source))
    return result.replace('<html lang="fa" dir="rtl">', '<html lang="en" dir="ltr">', 1)
