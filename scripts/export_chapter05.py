"""Export saved Chapter 5 plots, embedded explorer, and complete source ZIP."""
import base64
import hashlib
import json
from pathlib import Path
import zipfile
from geometry_assets import embed_geometry

ROOT=Path(__file__).resolve().parents[1]
destination=ROOT/'assets/chapter-05';destination.mkdir(parents=True,exist_ok=True)
notebooks={'05-beam-steering.ipynb':{'ch05-coverage':'coverage.png','ch05-orders':'orders.png','ch05-field':'field.png'},
           '05-wavefront-models.ipynb':{'ch05-focus':'focus.png','ch05-axial':'axial.png','ch05-polarization':'polarization.png'}}
for notebook,tags in notebooks.items():
    nb=json.loads((ROOT/'notebooks'/notebook).read_text(encoding='utf-8'))
    for tag,filename in tags.items():
        cells=[c for c in nb['cells'] if tag in c.get('metadata',{}).get('tags',[])]
        assert len(cells)==1 and cells[0].get('execution_count') is not None
        images=[o['data']['image/png'] for o in cells[0].get('outputs',[]) if 'image/png' in o.get('data',{})]
        assert len(images)==1
        data=images[0];(destination/filename).write_bytes(base64.b64decode(''.join(data) if isinstance(data,list) else data))
data=json.loads((ROOT/'data/chapter-05/beam-steering.json').read_text())
for name,digest in data['metadata']['source_sha256'].items():
    assert hashlib.sha256((ROOT/'simulations'/name).read_bytes()).hexdigest()==digest
template=embed_geometry((ROOT/'templates/synthesis-explorer.html').read_text(encoding='utf-8'))
assert template.count('__CH05_SYNTHESIS_DATA__')==1
(ROOT/'interactives/synthesis-explorer.html').write_text(template.replace('__CH05_SYNTHESIS_DATA__',json.dumps(data,separators=(',',':'))),encoding='utf-8')
files=['notebooks/05-beam-steering.ipynb','notebooks/05-wavefront-models.ipynb',
       'simulations/metasurface_synthesis.py','simulations/unit_cell_te.py',
       'requirements-labs.txt','requirements-validation.txt','scripts/validate_chapter05.py',
       'data/chapter-03/response-library.json','data/chapter-05/README.md',
       'data/chapter-05/beam-steering.json','data/chapter-05/extended-library.csv',
       'data/chapter-05/wavefront-models.json','data/chapter-05/validation.json',
       'interactives/synthesis-explorer.html','assets/chapter-05/supercell-geometry.svg']
with zipfile.ZipFile(ROOT/'downloads/chapter-05-synthesis.zip','w',compression=zipfile.ZIP_DEFLATED) as archive:
    for file in files:archive.write(ROOT/file,file)
    archive.writestr('START-HERE.md','''# Chapter 5 source bundle

Extract the complete ZIP. With Python 3.12, create a virtual environment and
install requirements-labs.txt. Launch JupyterLab in this folder and run
notebooks/05-beam-steering.ipynb before notebooks/05-wavefront-models.ipynb.
The second notebook uses the library generated by the first. Preserve the
simulations/ and data/ folders. The first notebook reads the original Chapter 3
library from data/chapter-03/ and writes Chapter 5 results into data/chapter-05/.

Restart each kernel and run all cells. Optional independent implementation audit:
install requirements-validation.txt and run scripts/validate_chapter05.py --grcwa
from this folder. The saved audit describes the published reference, not a
changed physical experiment. Rerun and version validation when editing parameters.
The scalar line-focus and ideal Jones models are separate from full-wave TE
ridge simulations; retain those evidence labels in reports.
''')
print('Exported six figures, synthesis explorer, and downloads/chapter-05-synthesis.zip')
